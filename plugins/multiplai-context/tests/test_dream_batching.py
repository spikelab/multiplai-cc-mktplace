class TestFoldPendingProposals:
    def test_undecided_generated_proposal_is_folded_and_superseded(self, dream_env):
        mod = _load_dream("dream_fold_ok")
        dreams_dir = dream_env["dreams_dir"]
        path = _write_generated(mod, dreams_dir, "processed-learnings-2026-07-30.md")

        folded = mod._fold_pending_proposals(dreams_dir)

        assert len(folded) == 1
        assert "Always fetch before comparing to a remote" in folded[0]
        assert not path.exists(), "the folded proposal must leave the dreams root"
        superseded = list((dreams_dir / "superseded").glob("*.md"))
        assert [p.name for p in superseded] == ["processed-learnings-2026-07-30.md"]

    def test_proposal_with_processed_items_is_left_strictly_alone(self, dream_env):
        """`## Processed` is the cross-tool contract — folding discards decisions."""
        mod = _load_dream("dream_fold_decided")
        dreams_dir = dream_env["dreams_dir"]
        path = _write_generated(mod, dreams_dir, "processed-learnings-2026-07-30.md",
                                DECIDED_BODY)

        assert mod._fold_pending_proposals(dreams_dir) == []
        assert path.exists()
        assert not (dreams_dir / "superseded").exists()

    def test_hand_curated_proposal_is_not_folded(self, dream_env):
        """Spike curates by deleting items; the remainder IS the approval."""
        mod = _load_dream("dream_fold_curated")
        dreams_dir = dream_env["dreams_dir"]
        path = _write_generated(mod, dreams_dir, "processed-learnings-2026-07-30.md")
        curated = path.read_text().replace(
            "> Run `git fetch` before checking ahead/behind counts.\n", ""
        )
        path.write_text(curated)

        assert mod._fold_pending_proposals(dreams_dir) == []
        assert path.exists()
        assert path.read_text() == curated, "a curated proposal must not be touched"

    def test_touched_but_unchanged_proposal_is_still_folded(self, dream_env):
        """mtime is not the criterion: git checkout/stash rewrite mtimes."""
        mod = _load_dream("dream_fold_touched")
        dreams_dir = dream_env["dreams_dir"]
        path = _write_generated(mod, dreams_dir, "processed-learnings-2026-07-30.md")
        before = path.read_bytes()
        os.utime(path, (0, 0))
        assert path.stat().st_mtime == 0

        folded = mod._fold_pending_proposals(dreams_dir)

        assert len(folded) == 1
        assert not path.exists()
        assert (dreams_dir / "superseded" /
                "processed-learnings-2026-07-30.md").read_bytes() == before

    def test_pre_ledger_proposal_without_stamp_is_not_folded(self, dream_env):
        mod = _load_dream("dream_fold_preledger")
        dreams_dir = dream_env["dreams_dir"]
        path = dreams_dir / "processed-learnings-2026-07-29.md"
        path.write_text(PROPOSAL_BODY)

        assert mod._fold_pending_proposals(dreams_dir) == []
        assert path.exists()

    def test_superseding_is_collision_safe(self, dream_env):
        mod = _load_dream("dream_fold_collide")
        dreams_dir = dream_env["dreams_dir"]
        (dreams_dir / "superseded").mkdir()
        (dreams_dir / "superseded" / "processed-learnings-2026-07-30.md").write_text("old")
        _write_generated(mod, dreams_dir, "processed-learnings-2026-07-30.md")

        assert len(mod._fold_pending_proposals(dreams_dir)) == 1
        names = sorted(p.name for p in (dreams_dir / "superseded").glob("*.md"))
        assert names == [
            "processed-learnings-2026-07-30.md",
            "processed-learnings-2026-07-30-2.md",
        ] or names == [
            "processed-learnings-2026-07-30-2.md",
            "processed-learnings-2026-07-30.md",
        ]
        assert (dreams_dir / "superseded" /
                "processed-learnings-2026-07-30.md").read_text() == "old"


