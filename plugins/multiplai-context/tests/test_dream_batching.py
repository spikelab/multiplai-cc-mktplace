class TestLedgerCoverage:
    def test_a_dropped_draft_un_records_its_blocks(self, dream_env):
        """Recording a block whose draft never reached the merge is silent loss."""
        mod = _load_dream("dream_coverage_bad")
        blocks = _blocks(mod, 1)
        run_dir = mod._runs_dir() / "run-a"
        mod._stage_draft(run_dir, 1, "DRAFT A", [b.key for b in blocks])
        ledger_path = mod.learnings_ledger.default_ledger_path()
        mod.learnings_ledger.record(ledger_path, blocks, "p.md")

        # Merge input does NOT contain the staged draft.
        mod._enforce_ledger_coverage(ledger_path, run_dir, ["something else"])

        ledger = mod.learnings_ledger.load(ledger_path)
        assert blocks[0].key not in ledger["processed"], (
            "a block whose draft was dropped must be re-consolidated next run"
        )

    def test_a_merged_draft_keeps_its_record(self, dream_env):
        mod = _load_dream("dream_coverage_ok")
        blocks = _blocks(mod, 1)
        run_dir = mod._runs_dir() / "run-a"
        mod._stage_draft(run_dir, 1, "DRAFT A", [b.key for b in blocks])
        ledger_path = mod.learnings_ledger.default_ledger_path()
        mod.learnings_ledger.record(ledger_path, blocks, "p.md")

        mod._enforce_ledger_coverage(ledger_path, run_dir, ["DRAFT A"])

        assert blocks[0].key in mod.learnings_ledger.load(ledger_path)["processed"]


