def _chunks(mod, n: int):
    """Real Chunk objects, one block each, so `render_chunk` has real input."""
    from lib.dream_chunking import Chunk

    blocks = _blocks(mod, n)
    return [
        Chunk(
            index=i + 1,
            blocks=(b,),
            n_bytes=len(b.text.encode("utf-8")),
            timeout_s=mod.CHUNK_TIMEOUT_S,
            oversized=False,
        )
        for i, b in enumerate(blocks)
    ]


def _client(responses):
    """A client whose query() returns/raises the next item of *responses*."""
    calls = []

    async def query(*, system, messages, **kwargs):
        item = responses[len(calls)]
        calls.append(kwargs)
        if isinstance(item, Exception):
            raise item
        response = MagicMock()
        response.content = item
        return response

    client = MagicMock()
    client.query = query
    client.calls = calls
    return client


async def _draft(mod, client, chunks, run_dir):
    return await mod._draft_chunks(
        client, chunks,
        memory_context="### dev.md\nSECTIONS:\n# Dev",
        source_names="2026-07-30.md",
        run_dir=run_dir,
        ledger_path=mod.learnings_ledger.default_ledger_path(),
        proposal_name="processed-learnings-2026-07-30.md",
    )


class TestChunkedDraft:
    def test_one_failed_chunk_is_skipped_and_stays_unprocessed(self, dream_env):
        mod = _load_dream("dream_chunk_partial")
        chunks = _chunks(mod, 2)
        client = _client([RuntimeError("boom"), "## Updates for `dev.md`\n\n### 1. ok\n"])
        run_dir = mod._runs_dir() / "run-a"

        drafts = asyncio.run(_draft(mod, client, chunks, run_dir))

        assert len(drafts) == 1
        processed = mod.learnings_ledger.load(
            mod.learnings_ledger.default_ledger_path()
        )["processed"]
        assert chunks[0].blocks[0].key not in processed, (
            "a failed chunk's blocks must stay unprocessed for the next run"
        )
        assert chunks[1].blocks[0].key in processed

    def test_every_chunk_failing_re_raises(self, dream_env):
        """A total failure is an outage — writing an empty proposal would look
        like success."""
        mod = _load_dream("dream_chunk_total")
        chunks = _chunks(mod, 2)
        client = _client([RuntimeError("boom"), RuntimeError("boom")])

        with pytest.raises(RuntimeError):
            asyncio.run(_draft(mod, client, chunks, mod._runs_dir() / "run-a"))

    def test_successful_chunks_are_staged_before_the_run_ends(self, dream_env):
        mod = _load_dream("dream_chunk_stage")
        chunks = _chunks(mod, 2)
        client = _client(["DRAFT ONE", "DRAFT TWO"])
        run_dir = mod._runs_dir() / "run-a"

        asyncio.run(_draft(mod, client, chunks, run_dir))

        staged = sorted(p.name for p in run_dir.glob("*.md"))
        assert staged == ["chunk-01.md", "chunk-02.md"]

    def test_per_chunk_timeout_is_passed_through(self, dream_env):
        mod = _load_dream("dream_chunk_timeout")
        chunks = _chunks(mod, 1)
        client = _client(["DRAFT"])

        asyncio.run(_draft(mod, client, chunks, mod._runs_dir() / "run-a"))

        assert client.calls[0].get("timeout_s") == chunks[0].timeout_s

    def test_older_core_without_timeout_kwarg_still_works(self, dream_env):
        """PR B adds query(timeout_s=…); an older pin must not break the run."""
        mod = _load_dream("dream_chunk_oldcore")
        chunks = _chunks(mod, 1)

        seen = []

        async def query(*, system, messages, **kwargs):
            if "timeout_s" in kwargs:
                raise TypeError("query() got an unexpected keyword argument 'timeout_s'")
            seen.append(kwargs)
            response = MagicMock()
            response.content = "DRAFT"
            return response

        client = MagicMock()
        client.query = query

        drafts = asyncio.run(_draft(mod, client, chunks, mod._runs_dir() / "run-a"))

        assert drafts == ["DRAFT"]
        assert seen == [{}]

    def test_concurrency_default_and_override(self, dream_env, monkeypatch):
        mod = _load_dream("dream_concurrency")
        assert mod._concurrency() == 4
        monkeypatch.setenv("MULTIPLAI_DREAM_CONCURRENCY", "2")
        assert mod._concurrency() == 2
        monkeypatch.setenv("MULTIPLAI_DREAM_CONCURRENCY", "nonsense")
        assert mod._concurrency() == 4


