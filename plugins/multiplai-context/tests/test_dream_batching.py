DRAFT_RESPONSE = """\
# Processed Learnings — 2026-07-30

## Updates for `dev.md`

### 1. A drafted lesson
**Change:** add
> Do the thing.

**Source:** 2026-07-30.md:3

---

## Filtered Out (1 items)

**diary/event-only**
- Shipped it — records what happened (Source: 2026-07-30.md:9)
"""


def _report_client():
    """Drafts return a proposal; the critic returns NOOP (fail-open, no edits)."""
    async def query(*, system, messages, **kwargs):
        response = MagicMock()
        response.content = "NOOP" if system.startswith("You are a strict editor") \
            else DRAFT_RESPONSE
        return response

    client = MagicMock()
    client.query = query
    return client


def _release_lock(mod):
    """Drop the in-process lock so a follow-up run can be simulated."""
    if mod._RUN_LOCK_FD is not None:
        os.close(mod._RUN_LOCK_FD)
        mod._RUN_LOCK_FD = None


class TestReportRunEndToEnd:
    @pytest.fixture
    def seeded(self, dream_env):
        mod = _load_dream("dream_e2e")
        learnings = dream_env["learnings_dir"] / "2026-07-30.md"
        learnings.write_text("\n".join(
            f"## Session Learnings — 2026-07-30T0{i}:00:00+00:00\n"
            f"Session: s{i}\n"
            f"- **[trust: verified]** PATTERN Lesson {i}. → Target: dev.md\n\n---\n"
            for i in range(3)
        ))
        mod.create_client = AsyncMock(return_value=_report_client())
        return mod, learnings

    def test_one_run_writes_one_stamped_proposal(self, seeded, dream_env):
        mod, learnings = seeded
        before = learnings.read_bytes()

        asyncio.run(mod.dream_report())

        written = list(dream_env["dreams_dir"].glob("processed-learnings-*.md"))
        assert len(written) == 1, "a run must leave exactly one pending proposal"
        assert mod._is_unmodified_generated(written[0].read_text())
        assert learnings.read_bytes() == before, "learnings are never moved or rewritten"
        assert learnings.exists()

    def test_blocks_are_ledgered_and_staging_is_cleared(self, seeded):
        mod, _ = seeded
        asyncio.run(mod.dream_report())

        processed = mod.learnings_ledger.load(
            mod.learnings_ledger.default_ledger_path()
        )["processed"]
        assert len(processed) == 3
        assert list(mod._runs_dir().iterdir()) == [], (
            "staged drafts are now inside a written proposal; keeping them would "
            "fold the same content in again next run"
        )

    def test_a_pending_undecided_proposal_is_folded_in(self, seeded, dream_env):
        mod, _ = seeded
        _write_generated(mod, dream_env["dreams_dir"], "processed-learnings-2026-07-29.md")

        asyncio.run(mod.dream_report())

        assert len(list(dream_env["dreams_dir"].glob("processed-learnings-*.md"))) == 1
        assert (dream_env["dreams_dir"] / "superseded" /
                "processed-learnings-2026-07-29.md").exists()
        written = next(dream_env["dreams_dir"].glob("processed-learnings-*.md")).read_text()
        assert "Always fetch before comparing to a remote" in written, (
            "the folded proposal's entries must survive into this run's document"
        )
        assert written.count("## Routing Warnings") == 1, (
            "the folded copy's regenerated sections must not be merged in"
        )
        assert written.count("<!-- dream:generated") == 1

    def test_a_second_run_finds_nothing_new(self, seeded, dream_env, capsys):
        mod, _ = seeded
        asyncio.run(mod.dream_report())
        _release_lock(mod)
        capsys.readouterr()

        asyncio.run(mod.dream_report())

        assert "No new learnings" in capsys.readouterr().out
        assert len(list(dream_env["dreams_dir"].glob("processed-learnings-*.md"))) == 1

    def test_a_hand_edited_proposal_survives_the_next_run(self, seeded, dream_env):
        """Done-means 14: curation is preserved and this run gets a -2 suffix."""
