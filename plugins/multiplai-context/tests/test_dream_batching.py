class TestRunLock:
    """A second concurrent run is a no-op, not an error."""

    def test_second_acquisition_is_refused(self, dream_env, capsys):
        mod = _load_dream("dream_lock_basic")
        assert mod.acquire_run_lock() is True
        # flock is per open file description, so a second open() in this same
        # process contends exactly as another container's process would.
        assert mod.acquire_run_lock() is False
        out = capsys.readouterr().out
        assert "Another dream run is already in progress" in out
        assert "started" in out, "the message must name the holder's start time"

    def test_lock_file_carries_an_iso_start_time(self, dream_env):
        mod = _load_dream("dream_lock_stamp")
        assert mod.acquire_run_lock() is True
        from datetime import datetime

        stamp = mod._lock_path().read_text().strip()
        # Round-trips as an ISO timestamp — that string is what the contention
        # message shows the second run.
        assert datetime.fromisoformat(stamp)

    def test_lock_lives_in_the_workspace_not_tmp(self, dream_env):
        """A /tmp lock is container-local — two sessions would both proceed."""
        mod = _load_dream("dream_lock_path")
        assert mod.acquire_run_lock() is True
        assert str(mod._lock_path()).startswith(str(dream_env["data_dir"]))

    def test_second_report_run_exits_without_writing_a_proposal(self, dream_env):
        mod = _load_dream("dream_lock_report")
        assert mod.acquire_run_lock() is True

        client = AsyncMock()
        mod.create_client = AsyncMock(return_value=client)
        asyncio.run(mod.dream_report())

        client.query.assert_not_awaited()
        assert list(dream_env["dreams_dir"].glob("*.md")) == []

    def test_check_answers_while_a_run_holds_the_lock(self, dream_env, capsys, monkeypatch):
        """--check must work mid-run — that is most of the point of having it."""
        mod = _load_dream("dream_lock_check")
        (dream_env["learnings_dir"] / "2026-07-30.md").write_text(
            "## Session Learnings — 2026-07-30T01:00:00+00:00\n"
            "Session: s1\n- **[trust: verified]** PATTERN A lesson. → Target: dev.md\n"
        )
        assert mod.acquire_run_lock() is True
        capsys.readouterr()

        monkeypatch.setattr("sys.argv", ["dream.py", "--check"])
        mod.main()

        out = capsys.readouterr().out
        assert "Another dream run is already in progress" not in out
        assert "Pending learnings:" in out
        assert "Dream plan:" in out
        assert "Estimated wall clock:" in out


