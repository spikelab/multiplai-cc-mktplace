def _blocks(mod, count: int = 2):
    from lib.learnings_ledger import parse_blocks

    text = "\n".join(
        f"## Session Learnings — 2026-07-30T0{i}:00:00+00:00\n"
        f"Session: abc-{i}\n"
        f"- **[trust: verified]** PATTERN Lesson {i}. → Target: dev.md\n\n---\n"
        for i in range(count)
    )
    return parse_blocks("2026-07-30.md", text)


class TestStagingAndResume:
    def test_staged_draft_and_sidecar_are_written(self, dream_env):
        mod = _load_dream("dream_stage")
        run_dir = mod._runs_dir() / "run-a"
        blocks = _blocks(mod, 1)

        md = mod._stage_draft(run_dir, 3, "DRAFT", [b.key for b in blocks])

        assert md.name == "chunk-03.md"
        assert md.read_text() == "DRAFT"
        meta = json.loads((run_dir / "chunk-03.json").read_text())
        assert meta["keys"] == [blocks[0].key]

    def test_ledgered_staged_draft_is_resumed(self, dream_env):
        mod = _load_dream("dream_resume_ok")
        blocks = _blocks(mod, 1)
        old_run = mod._runs_dir() / "run-old"
        mod._stage_draft(old_run, 1, "STAGED DRAFT", [b.key for b in blocks])

        ledger_path = mod.learnings_ledger.default_ledger_path()
        mod.learnings_ledger.record(ledger_path, blocks, "processed-learnings-x.md")
        ledger = mod.learnings_ledger.load(ledger_path)

        resumed = mod._resume_staged_drafts(mod._runs_dir() / "run-new", ledger)

        assert resumed == ["STAGED DRAFT"]

    def test_unledgered_staged_draft_is_discarded(self, dream_env):
        """Its blocks are being re-drafted now — keeping it would duplicate them."""
        mod = _load_dream("dream_resume_stale")
        blocks = _blocks(mod, 1)
        old_run = mod._runs_dir() / "run-old"
        md = mod._stage_draft(old_run, 1, "STALE", [b.key for b in blocks])

        ledger = {"version": 1, "processed": {}}
        assert mod._resume_staged_drafts(mod._runs_dir() / "run-new", ledger) == []
        assert not md.exists()

    def test_keyless_draft_is_always_resumed(self, dream_env):
        """A folded proposal has no blocks; it must survive a crashed run."""
        mod = _load_dream("dream_resume_folded")
        old_run = mod._runs_dir() / "run-old"
        mod._stage_draft(old_run, 1, "FOLDED", [], kind="folded")

        ledger = {"version": 1, "processed": {}}
        assert mod._resume_staged_drafts(mod._runs_dir() / "run-new", ledger) == ["FOLDED"]

    def test_current_run_dir_is_not_resumed(self, dream_env):
        mod = _load_dream("dream_resume_self")
        run_dir = mod._runs_dir() / "run-now"
        mod._stage_draft(run_dir, 1, "MINE", [])
        assert mod._resume_staged_drafts(run_dir, {"processed": {}}) == []

    def test_clear_staging_removes_every_run_dir(self, dream_env):
        mod = _load_dream("dream_clear")
        mod._stage_draft(mod._runs_dir() / "run-a", 1, "A", [])
        mod._stage_draft(mod._runs_dir() / "run-b", 1, "B", [])
        mod._clear_staging()
        assert list(mod._runs_dir().iterdir()) == []


