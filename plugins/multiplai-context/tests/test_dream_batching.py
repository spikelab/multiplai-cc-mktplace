"""Tests for dream's batching pipeline — the lock, the single-proposal fold, and
per-chunk staging/resume.

These cover the parts of `dream.py` that decide *whether* work happens and *what
survives a crash*. The pure libraries they lean on (`learnings_ledger`,
`dream_chunking`, `proposal_merge`, `proposal_edits`) have their own unit suites;
nothing here re-tests those.

Two properties are asserted hardest because getting them wrong is unrecoverable:

- a proposal a human has edited is NEVER folded (hand-curation is a supported
  workflow — Spike approves by deleting the items he does not want — and folding
  such a file destroys the curation), and the guard keys on CONTENT, not mtime,
  because `.multiplai/dreams/` is git-tracked and checkout rewrites mtimes;
- a block is never left recorded in the ledger when its draft did not reach the
  merge. That is silent learning loss: the block never resurfaces and nobody
  ever sees it.
"""

import asyncio
import importlib.util
import json
import os
from pathlib import Path
from unittest.mock import AsyncMock, MagicMock

import pytest

from conftest import PLUGIN_ROOT, SCRIPTS_DIR


def _load_dream(alias: str):
    """Load dream.py as an isolated module (fresh paths cache) per test."""
    from multiplai_core.paths import _reset_cache

    _reset_cache()
    spec = importlib.util.spec_from_file_location(alias, SCRIPTS_DIR / "dream.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


@pytest.fixture
def dream_env(tmp_path, monkeypatch):
    """A dream workspace rooted at tmp_path, with paths resolved fresh."""
    data_dir = tmp_path / "data"
    memory_dir = tmp_path / "memory"
    for d in (data_dir, memory_dir, data_dir / "catalogs"):
        d.mkdir(parents=True, exist_ok=True)

    monkeypatch.setenv("CLAUDE_PLUGIN_DATA", str(data_dir))
    monkeypatch.setenv("CLAUDE_PLUGIN_ROOT", str(PLUGIN_ROOT))
    monkeypatch.setenv("CLAUDE_PLUGIN_OPTION_memory_dir", str(memory_dir))

    from multiplai_core.paths import _reset_cache, get_paths

    _reset_cache()
    paths = get_paths()
    paths.learnings_dir.mkdir(parents=True, exist_ok=True)
    paths.dreams_dir().mkdir(parents=True, exist_ok=True)
    (memory_dir / "dev.md").write_text("# Dev\n\n## Tooling\n")
    return {
        "data_dir": data_dir,
        "memory_dir": memory_dir,
        "learnings_dir": paths.learnings_dir,
        "dreams_dir": paths.dreams_dir(),
    }


# A proposal shaped exactly like what dream writes: one pending update entry
# with its provenance line. `has_pending_items` needs the `## Updates for`
# grouping to see anything at all.
PROPOSAL_BODY = """\
# Processed Learnings — 2026-07-30

**Sources:** 1 files, ~2 entries
Generated by Dream. Review with `/multiplai-context:dream-remember` to apply.

---

## Updates for `dev.md`

### 1. Always fetch before comparing to a remote
**Section:** Tooling
**Change:** add
> Run `git fetch` before checking ahead/behind counts.

**Source:** 2026-07-30.md:12

---

## Filtered Out (1 items)

**diary/event-only**
- Shipped the thing — records what happened (Source: 2026-07-30.md:20)
"""

DECIDED_BODY = PROPOSAL_BODY + """
---

## Processed

_Items decided via `/dream-remember` or the GUI._

### 2. A decided entry
**Processed:** applied → dev.md · 2026-07-30T10:00:00Z
**Source:** 2026-07-30.md:30
"""


def _write_generated(mod, dreams_dir: Path, name: str, body: str = PROPOSAL_BODY) -> Path:
    path = dreams_dir / name
    path.write_text(mod._stamp_generated(body))
    return path


