class TestBatchMarking:
    def test_marks_every_decision_in_one_call(self, tmp_path):
        p = _proposal(tmp_path)
        marked, unchanged = mark_many_processed(p, FIXTURE_DECISIONS, ts=TS)
        assert (marked, unchanged) == (5, 0)
        out = p.read_text()
        # Every decided item now sits under ## Processed, none above it.
        head, _, tail = out.partition("## Processed")
        assert "### 1. Worktrees are the default" not in head
        assert "### A2. Garbage-collect" not in head
        assert _annotations(tail) == 5

    def test_spans_several_files_and_both_kinds(self, tmp_path):
        p = _proposal(tmp_path)
        mark_many_processed(p, FIXTURE_DECISIONS, ts=TS)
        tail = p.read_text().split("## Processed", 1)[1]
        assert "### 1. Worktrees are the default" in tail
        assert "### 1. Prefer uv over pip" in tail
        assert "### A1. Batch the mark-processed calls" in tail

    def test_already_processed_items_count_as_unchanged(self, tmp_path):
        p = _proposal(tmp_path)
        mark_many_processed(p, FIXTURE_DECISIONS, ts=TS)
        before = p.read_text()
        marked, unchanged = mark_many_processed(p, FIXTURE_DECISIONS, ts=TS)
        assert (marked, unchanged) == (0, 5)
        assert p.read_text() == before  # idempotent, and no rewrite

    def test_unsorted_indices_match_descending_order(self):
        descending = [
            Decision("update", 2, "rejected", file="git-policy.md"),
            Decision("update", 1, "applied", file="git-policy.md", target="git-policy.md"),
        ]
        unsorted = list(reversed(descending))
        assert (
            move_many_to_processed(PENDING, unsorted, ts=TS)
            == move_many_to_processed(PENDING, descending, ts=TS)
        )

    def test_batch_matches_the_same_decisions_applied_one_at_a_time(self):
        """The stop-and-ask gate: a batched call must not differ *in any way*
        from N single-flag calls, or two writers of the same proposal disagree
        about what a decided item looks like."""
        batched, _ = move_many_to_processed(PENDING, FIXTURE_DECISIONS, ts=TS)
        assert batched == _sequential(PENDING, order_decisions(FIXTURE_DECISIONS))

    def test_batch_matches_the_hub_writer_format(self):
        """Fixture test against multiplai-gui's independent native writer."""
        batched, _ = move_many_to_processed(PENDING, FIXTURE_DECISIONS, ts=TS)
        assert _NOTE_RE.sub("<note>", batched) == _NOTE_RE.sub("<note>", HUB_OUTPUT)

    def test_the_only_divergence_from_the_hub_is_the_note_line(self):
        # Stated explicitly so a future change that introduces a *second*
        # difference fails here rather than silently widening the gap.
        batched, _ = move_many_to_processed(PENDING, FIXTURE_DECISIONS, ts=TS)
        ours = batched.splitlines()
        theirs = HUB_OUTPUT.splitlines()
        assert len(ours) == len(theirs)
        differing = [i for i, (a, b) in enumerate(zip(ours, theirs)) if a != b]
        assert len(differing) == 1
        assert _NOTE_RE.match(ours[differing[0]])
        assert _NOTE_RE.match(theirs[differing[0]])

    def test_empty_batch_is_a_no_op(self, tmp_path):
        p = _proposal(tmp_path)
        assert mark_many_processed(p, [], ts=TS) == (0, 0)
        assert p.read_text() == PENDING


class TestBatchPartialFailure:
    def test_unwritable_target_leaves_the_file_byte_identical(self, tmp_path):
        d = tmp_path / "dreams"
        d.mkdir()
        p = _proposal(d)
        original = p.read_bytes()
        d.chmod(0o500)  # readable, not writable: mkstemp fails
        try:
            with pytest.raises(OSError):
                mark_many_processed(p, FIXTURE_DECISIONS, ts=TS)
            assert p.read_bytes() == original
        finally:
            d.chmod(0o700)

    def test_no_temp_file_is_left_behind(self, tmp_path):
        d = tmp_path / "dreams"
        d.mkdir()
        p = _proposal(d)
        mark_many_processed(p, FIXTURE_DECISIONS, ts=TS)
        assert [f.name for f in d.iterdir()] == [p.name]


class TestDecisionParsing:
    def test_defaults_kind_to_update(self):
        d = Decision.from_dict({"file": "a.md", "index": 1, "status": "applied"})
        assert d.kind == "update"

    def test_update_without_file_is_rejected(self):
        with pytest.raises(ValueError, match="needs a 'file'"):
            Decision.from_dict({"kind": "update", "index": 1, "status": "applied"})

    def test_bad_status_is_rejected(self):
        with pytest.raises(ValueError, match="status must be"):
            Decision.from_dict({"kind": "action", "index": 1, "status": "approve"})

    def test_hub_intent_vocabulary_is_not_accepted(self):
        # `approve`/`reject`/`edit` are the hub's *intent* words; this flag
        # records *outcomes*. Blurring them would log an unapplied item as done.
        for status in ("approve", "reject", "edit"):
            with pytest.raises(ValueError):
                Decision.from_dict({"kind": "action", "index": 1, "status": status})

    def test_bad_index_is_rejected(self):
        with pytest.raises(ValueError, match="index must be"):
            Decision.from_dict({"kind": "action", "index": "1", "status": "applied"})

    def test_boolean_index_is_rejected(self):
        with pytest.raises(ValueError, match="index must be"):
            Decision.from_dict({"kind": "action", "index": True, "status": "applied"})

    def test_non_object_is_rejected(self):
        with pytest.raises(ValueError, match="must be an object"):
            Decision.from_dict(["update", 1])


