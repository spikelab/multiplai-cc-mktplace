class TestOrderDecisions:
    def test_descending_index_within_a_group(self):
        ds = [
            Decision("update", 1, "applied", file="git-policy.md"),
            Decision("update", 2, "rejected", file="git-policy.md"),
        ]
        assert [d.index for d in order_decisions(ds)] == [2, 1]

    def test_groups_keep_first_appearance_order(self):
        # Sorting the groups instead would reorder the appended blocks and stop
        # the batch from matching the same decisions applied one at a time.
        ds = [
            Decision("update", 1, "applied", file="zzz.md"),
            Decision("action", 1, "applied"),
            Decision("update", 1, "applied", file="aaa.md"),
        ]
        assert [(d.kind, d.file) for d in order_decisions(ds)] == [
            ("update", "zzz.md"),
            ("action", None),
            ("update", "aaa.md"),
        ]

    def test_unsorted_input_orders_the_same_as_sorted(self):
        a = [
            Decision("update", 2, "applied", file="git-policy.md"),
            Decision("update", 1, "rejected", file="git-policy.md"),
        ]
        b = list(reversed(a))
        assert order_decisions(a) == order_decisions(b)


