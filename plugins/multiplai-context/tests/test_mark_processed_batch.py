def _run_dream(tmp_path, *args, stdin=None):
    env = os.environ.copy()
    env["WORKSPACE"] = str(tmp_path)
    return subprocess.run(
        [sys.executable, str(SCRIPTS_DIR / "dream.py"), *args],
        input=stdin,
        capture_output=True,
        text=True,
        env=env,
        timeout=120,
    )


def _stamp_ts(text):
    return re.sub(r"\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ", "<TS>", text)


class TestSingleItemCliRegression:
    """The single-flag form is what already-installed skill versions call. The
    batch form is strictly additive; this is the guard that it stayed that way.
    """

    EXPECTED_TAIL = """\
---

## Processed

_Items decided via `/dream-remember` or the GUI, moved here so they are no longer pending. Kept for history; delete the `**Processed:**` line and move a block back up to restore it._

### 1. Worktrees are the default for non-trivial work
**Processed:** applied → git-policy.md · <TS>
**Section:** Branching
**Change:** add
> Any multi-file change goes on a branch in a worktree.

**Source:** 2026-07-30.md:12
"""

    def test_single_flag_invocation_is_unchanged(self, tmp_path):
        p = _proposal(tmp_path)
        r = _run_dream(
            tmp_path, "--mark-processed", "--proposal", str(p),
            "--kind", "update", "--file", "git-policy.md", "--index", "1",
            "--status", "applied", "--target", "git-policy.md",
        )
        assert r.returncode == 0, r.stderr
        assert "Marked update git-policy.md#1 as applied" in r.stdout
        assert _stamp_ts(p.read_text()).endswith(self.EXPECTED_TAIL)

    def test_single_flag_action_item(self, tmp_path):
        p = _proposal(tmp_path)
        r = _run_dream(
            tmp_path, "--mark-processed", "--proposal", str(p),
            "--kind", "action", "--index", "1", "--status", "rejected",
        )
        assert r.returncode == 0, r.stderr
        assert "Marked action A1 as rejected" in r.stdout
        assert "**Processed:** rejected · " in p.read_text()

    def test_still_reports_no_change_for_an_unknown_item(self, tmp_path):
        p = _proposal(tmp_path)
        r = _run_dream(
            tmp_path, "--mark-processed", "--proposal", str(p),
            "--kind", "action", "--index", "99", "--status", "applied",
        )
        assert r.returncode == 0, r.stderr
        assert "No change" in r.stdout
        assert p.read_text() == PENDING


class TestBatchCli:
    def _payload(self):
        return json.dumps([
            {"kind": "update", "file": "git-policy.md", "index": 1,
             "status": "applied", "target": "git-policy.md"},
            {"kind": "update", "file": "git-policy.md", "index": 2, "status": "rejected"},
            {"kind": "update", "file": "technical-pref.md", "index": 1,
             "status": "edited", "target": "technical-pref.md"},
            {"kind": "action", "index": 1, "status": "applied"},
            {"kind": "action", "index": 2, "status": "rejected"},
        ])

    def test_stdin_array_marks_everything_in_one_call(self, tmp_path):
        p = _proposal(tmp_path)
        r = _run_dream(
            tmp_path, "--mark-processed", "--proposal", str(p), "--decisions", "-",
            stdin=self._payload(),
        )
        assert r.returncode == 0, r.stderr
        assert "marked 5 processed, 0 unchanged" in r.stdout
        assert _annotations(p.read_text().split("## Processed", 1)[1]) == 5

    def test_batch_cli_equals_five_single_flag_calls(self, tmp_path):
        """Criterion 15: one batched call and N single-flag calls must produce
        the same file (timestamps normalized — the clock is not the contract)."""
        a = _proposal(tmp_path, name="A.md")
        b = _proposal(tmp_path, name="B.md")
        _run_dream(tmp_path, "--mark-processed", "--proposal", str(a),
                   "--decisions", "-", stdin=self._payload())
        for d in order_decisions(FIXTURE_DECISIONS):
            args = ["--mark-processed", "--proposal", str(b), "--kind", d.kind,
                    "--index", str(d.index), "--status", d.status]
            if d.file:
                args += ["--file", d.file]
            if d.target:
                args += ["--target", d.target]
            r = _run_dream(tmp_path, *args)
            assert r.returncode == 0, r.stderr
        assert _stamp_ts(a.read_text()) == _stamp_ts(b.read_text())

    def test_decisions_from_a_file(self, tmp_path):
        p = _proposal(tmp_path)
        payload = tmp_path / "decisions.json"
        payload.write_text(self._payload())
        r = _run_dream(tmp_path, "--mark-processed", "--proposal", str(p),
                       "--decisions", str(payload))
        assert r.returncode == 0, r.stderr
        assert "marked 5 processed" in r.stdout

    def test_malformed_json_exits_two_and_writes_nothing(self, tmp_path):
        p = _proposal(tmp_path)
        r = _run_dream(tmp_path, "--mark-processed", "--proposal", str(p),
                       "--decisions", "-", stdin="not json")
        assert r.returncode == 2
        assert "ERROR: --decisions could not be read" in r.stdout
        assert p.read_text() == PENDING

    def test_invalid_decision_exits_two_and_writes_nothing(self, tmp_path):
        p = _proposal(tmp_path)
        r = _run_dream(tmp_path, "--mark-processed", "--proposal", str(p),
                       "--decisions", "-",
                       stdin='[{"kind":"update","index":1,"status":"applied"}]')
        assert r.returncode == 2
        assert p.read_text() == PENDING

    def test_missing_proposal_is_an_error(self, tmp_path):
        r = _run_dream(tmp_path, "--mark-processed", "--decisions", "-", stdin="[]")
        assert r.returncode == 2
        assert "needs --proposal" in r.stdout

    def test_unwritable_dir_exits_nonzero_leaving_the_proposal_intact(self, tmp_path):
        d = tmp_path / "dreams"
        d.mkdir()
        p = _proposal(d)
        original = p.read_bytes()
        d.chmod(0o500)
        try:
            r = _run_dream(tmp_path, "--mark-processed", "--proposal", str(p),
                           "--decisions", "-", stdin=self._payload())
            assert r.returncode == 1
            assert "proposal unchanged" in r.stdout
            assert p.read_bytes() == original
        finally:
            d.chmod(0o700)


