"""Batched ``--mark-processed`` and the deterministic ``--gc-learnings``.

Why these exist. A `/dream-remember` review of a real proposal decides 50–70
items, and the pre-batch apply path spent one `uv run` cold start per item — a
fresh interpreter and environment check, to move text inside one local file. On 2026-07-24 a 70-item review applied five files and then ran out
of context mid-review. The batch path collapses that to one call per target
file; these tests hold it to producing *exactly* what the per-item path did.

Two contracts are asserted, not assumed:

1. **Batch == sequential.** Every writer of a decided proposal must agree
   byte-for-byte on what one looks like, or two tools reviewing the same file
   disagree about what is pending.
2. **Batch == the hub's independent writer.** ``tests/fixtures/`` holds a
   pending proposal and the document multiplai-gui's hub produces from it.
   ``proposal_processed_by_hub.md`` was generated by running the hub's own
   ``multiplai_hub.dreams.move_to_processed`` (from the multiplai-gui checkout)
   over ``proposal_pending.md`` with ts ``2026-07-31T09:00:00Z`` and the five
   decisions in :data:`FIXTURE_DECISIONS`, in canonical order. Regenerate it
   from the hub, never by hand — a hand-edited fixture asserts nothing.
"""

import json
import os
import re
import subprocess
import sys
from pathlib import Path

import pytest

from conftest import SCRIPTS_DIR
from lib.dream_processed import (
    Decision,
    mark_many_processed,
    mark_processed,
    move_many_to_processed,
    move_to_processed,
    order_decisions,
)

FIXTURES = Path(__file__).parent / "fixtures"
PENDING = (FIXTURES / "proposal_pending.md").read_text()
HUB_OUTPUT = (FIXTURES / "proposal_processed_by_hub.md").read_text()

TS = "2026-07-31T09:00:00Z"

# The decision set the hub fixture was generated from, in the order
# /dream-remember would emit it: all of one target file, then the next, then
# the action items.
FIXTURE_DECISIONS = [
    Decision("update", 1, "applied", file="git-policy.md", target="git-policy.md"),
    Decision("update", 2, "rejected", file="git-policy.md"),
    Decision("update", 1, "edited", file="technical-pref.md", target="technical-pref.md"),
    Decision("action", 1, "applied"),
    Decision("action", 2, "rejected"),
]

# The one place the two writers deliberately differ: the explanatory note under
# ``## Processed`` names the tools in the opposite order. Both modules' comments
# say the note is history that is never re-parsed; only the heading and the
# entries themselves are contract.
_NOTE_RE = re.compile(r"^_Items decided via .*restore it\._$", re.MULTILINE)


def _proposal(tmp_path, text=PENDING, name="processed-learnings-2026-07-31.md"):
    p = tmp_path / name
    p.write_text(text)
    return p


def _annotations(text):
    """Count `**Processed:**` *annotation lines* — the explanatory note under the
    heading mentions the marker too, and would otherwise be counted as an item."""
    return sum(1 for line in text.splitlines() if line.startswith("**Processed:**"))


def _sequential(text, decisions, ts=TS):
    """The same decisions applied one at a time, in the given order."""
    for d in decisions:
        text = move_to_processed(text, d.ref, d.status, target=d.target, ts=ts)
    return text


